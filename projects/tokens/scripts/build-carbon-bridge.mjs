/**
 * Generates carbon-bridge.css: the `--cds-*` -> `--color-*` mapping from carbon-bridge-map.mjs,
 * checked against theme.css so a bridge line can never point at a role that does not exist. The
 * file is committed so a change is reviewable in a diff; test/carbon-bridge.spec.mjs fails when
 * it is stale.
 *
 *   node projects/tokens/scripts/build-carbon-bridge.mjs     (npm run build:carbon-bridge at the root)
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

import {BRIDGE} from './carbon-bridge-map.mjs';

export const BRIDGE_FILE = fileURLToPath(new URL('../carbon-bridge.css', import.meta.url));
const THEME_FILE = fileURLToPath(new URL('../theme.css', import.meta.url));

/** The `--color-*` roles theme.css defines. */
export function themeRoles(css = readFileSync(THEME_FILE, 'utf8')) {
  return new Set([...css.matchAll(/^\s*(--color-[a-z0-9-]+)\s*:/gm)].map(match => match[1]));
}

/** The `--color-*` roles a bridge value reads. */
export function rolesOf(value) {
  return [...value.matchAll(/var\((--color-[a-z0-9-]+)\)/g)].map(match => match[1]);
}

const MAX_LINE = 100;

/** One declaration, wrapped like Prettier wraps a long `color-mix()` so format:check passes. */
function declaration(name, value) {
  const line = `  --cds-${name}: ${value};`;
  const mix = value.match(/^color-mix\((.*)\)$/);
  if (line.length <= MAX_LINE || !mix) return line;
  const args = mix[1].split(/, (?![^(]*\))/).map(arg => `    ${arg}`);
  return [`  --cds-${name}: color-mix(`, args.join(',\n'), '  );'].join('\n');
}

/** The bridge stylesheet; throws if a line reads a role theme.css does not define. */
export function bridgeCss(roles = themeRoles()) {
  const names = new Set();
  const lines = BRIDGE.map(entry => {
    if (typeof entry === 'string') return `  /* ${entry.replace(/^\/\/\s*/, '')} */`;
    const [name, value] = entry;
    if (names.has(name)) throw new Error(`--cds-${name} is mapped twice`);
    names.add(name);
    for (const role of rolesOf(value)) {
      if (!roles.has(role)) throw new Error(`--cds-${name} reads ${role}, which theme.css lacks`);
    }
    return declaration(name, value);
  });
  return [
    '/*',
    ' * @lifekit-hq/tokens Carbon bridge: IBM Carbon colour names mapped onto the seed engine roles.',
    ' * Carbon reads colour only as var(--cds-NAME, fallback), so every Carbon-specced value follows',
    ' * the app seed and light/dark with no JS. Generated by scripts/build-carbon-bridge.mjs from',
    ' * carbon-bridge-map.mjs and theme.css; do not edit. Import after theme.css and the app seed.',
    ' */',
    ":root,\n[data-theme='light'],\n[data-theme='dark'] {",
    ...lines,
    '}',
    '',
  ].join('\n');
}

export function buildCarbonBridge() {
  writeFileSync(BRIDGE_FILE, bridgeCss());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildCarbonBridge();
}
