#!/usr/bin/env node
// Generates projects/ui/src/lib/components/icon/lucide-icon-set.ts: one named import per Lucide
// icon the library and the apps actually use, so a bundler keeps those icons and drops the other
// ~1,700. `IconComponent` used to import lucide-angular's whole `icons` map, which alone was ~440 KB
// of every consumer's bundle (issue #278).
//
// The set is the union of
//   - every quoted PascalCase string in the library sources (non-spec .ts under projects/ui/src and
//     projects/core/src) that is a Lucide icon name, and
//   - the names the apps use, listed in scripts/icon-set/consumers.json.
//
// It also writes projects/tokens/icons/lucide-icons.json (this subset plus the full Lucide catalog),
// the data behind `lifekit-chrome-check icons`: the gate that fails an app using an icon name that
// <cmn-icon> would render empty.
//
// Usage: node scripts/generate-icon-set.mjs [--check]   (--check fails when either file is stale)
import '@angular/compiler';
import {mkdirSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

import * as lucide from 'lucide-angular';
import * as prettier from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(root, 'projects/ui/src/lib/components/icon/lucide-icon-set.ts');
const CATALOG_OUTPUT = join(root, 'projects/tokens/icons/lucide-icons.json');
const CATALOG_LINE_WIDTH = 100;
const SOURCE_ROOTS = ['projects/ui/src', 'projects/core/src'].map(p => join(root, p));
const CONSUMERS = join(root, 'scripts/icon-set/consumers.json');
const QUOTED_PASCAL = /(['"`])([A-Z][A-Za-z0-9]*)\1/g;

const canonical = new Set(Object.keys(lucide.icons));

const sourceFiles = dir =>
  readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : sourceFiles(full);
    const isSource = entry.name.endsWith('.ts') && !entry.name.endsWith('.spec.ts');
    return isSource && full !== OUTPUT ? [full] : [];
  });

const used = new Set();
for (const dir of SOURCE_ROOTS) {
  for (const file of sourceFiles(dir)) {
    for (const [, , name] of readFileSync(file, 'utf8').matchAll(QUOTED_PASCAL)) {
      if (canonical.has(name)) used.add(name);
    }
  }
}

const consumers = JSON.parse(readFileSync(CONSUMERS, 'utf8'));
const unknown = [];
for (const [app, names] of Object.entries(consumers)) {
  if (app === '_') continue;
  for (const name of names) {
    if (canonical.has(name)) used.add(name);
    else unknown.push(`${app}: ${name}`);
  }
}
if (unknown.length > 0) {
  console.error('generate-icon-set: not a Lucide icon name in the installed lucide-angular:');
  for (const u of unknown) console.error(`  ${u}`);
  process.exit(1);
}

const names = [...used].sort((a, b) => a.localeCompare(b));
const source = `/* eslint-disable @typescript-eslint/naming-convention -- Lucide icon names are PascalCase. */
// GENERATED by scripts/generate-icon-set.mjs (npm run generate:icons). Do not edit.
// The Lucide icons <cmn-icon> can render: those the library and the apps use (${names.length} of ${canonical.size}).
// To add one, use it in the library or list it in scripts/icon-set/consumers.json, then regenerate.
// Apps can also register extra icons themselves with provideLucideIcons().
import type {LucideIcons} from 'lucide-angular';
import {
${names.map(n => `  ${n},`).join('\n')}
} from 'lucide-angular';

export const CMN_LUCIDE_ICONS: LucideIcons = {
${names.map(n => `  ${n},`).join('\n')}
};
`;

const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
const formatted = await prettier.format(source, {...config, filepath: OUTPUT});

// Names wrapped to CATALOG_LINE_WIDTH so a Lucide upgrade diffs as a handful of lines.
const wrapNames = list => {
  const lines = [];
  let line = '';
  for (const name of list) {
    const item = `"${name}",`;
    if (line && line.length + item.length + 1 > CATALOG_LINE_WIDTH) {
      lines.push(line);
      line = '';
    }
    line += line ? ` ${item}` : item;
  }
  if (line) lines.push(line);
  return lines
    .map(l => `    ${l}`)
    .join('\n')
    .replace(/,$/, '');
};
const catalogSource = `{
  "_": "GENERATED by scripts/generate-icon-set.mjs (npm run generate:icons). Do not edit. subset: the Lucide icons <cmn-icon> renders without the app registering anything. catalog: every Lucide icon name of the lucide-angular this version was built against.",
  "subset": [
${wrapNames(names)}
  ],
  "catalog": [
${wrapNames([...canonical].sort((a, b) => a.localeCompare(b)))}
  ]
}
`;

const read = file => {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return '';
  }
};

if (process.argv.includes('--check')) {
  const stale = [
    [OUTPUT, formatted],
    [CATALOG_OUTPUT, catalogSource],
  ].filter(([file, expected]) => read(file) !== expected);
  if (stale.length > 0) {
    for (const [file] of stale) {
      console.error(
        `generate-icon-set: ${relative(root, file)} is stale. Run \`npm run generate:icons\`.`
      );
    }
    process.exit(1);
  }
  console.log(`generate-icon-set: OK (${names.length} icons)`);
} else {
  writeFileSync(OUTPUT, formatted);
  mkdirSync(dirname(CATALOG_OUTPUT), {recursive: true});
  writeFileSync(CATALOG_OUTPUT, catalogSource);
  console.log(
    `generate-icon-set: wrote ${names.length} icons to ${relative(root, OUTPUT)} and ${relative(root, CATALOG_OUTPUT)}`
  );
}
